-- 清理历史遗留的接口级超时默认值 30000ms（30 秒）。
--
-- 背景：d9e2a65 之前，新建接口的 request_json 会写入硬编码的 timeout_ms: 30000；
-- 该版本把默认从 30s 改为 300s，并把 timeout_ms 变成 Option（NULL = 跟随全局
-- 设置）。但存量接口的显式 30000 被原样保留，于是在「设置 → 请求超时」显示
-- 300s 的同时，这些接口仍按 30s 取消——前端提示「请求超时（>30000ms），已自动
-- 取消」，与全局设置不符（用户实测反馈）。
--
-- 只清「恰好等于旧默认 30000」的值：d9e2a65 之后不可能再产生此默认（新建为
-- NULL），故现存 30000 均可判定为迁移残留。清空后这些接口回到「跟随全局」，
-- 与设置页一致。若用户确实想要 30 秒，重新在接口配置里填 30000 即可（此后
-- 该值与全局默认相同不再有歧义）。
UPDATE endpoints
SET request_json = json_remove(request_json, '$.timeout_ms')
WHERE json_extract(request_json, '$.timeout_ms') = 30000;